from __future__ import annotations

from typing import Protocol

import numpy as np

from dualarrow.models import EvidenceCandidate, KnowledgeUnit, SourceDocument


class VectorIndexAdapter(Protocol):
    async def initialize(self) -> None: ...
    async def close(self) -> None: ...
    async def replace_document(
        self, document: SourceDocument, units: list[KnowledgeUnit], embeddings: np.ndarray
    ) -> None: ...
    async def delete_document(self, document_id: str) -> None: ...
    async def delete_documents_not_in(self, document_ids: set[str]) -> int: ...
    async def search(self, vector: np.ndarray, top_k: int, filters: dict) -> list[EvidenceCandidate]: ...


class LexicalIndexAdapter(Protocol):
    async def initialize(self) -> None: ...
    async def close(self) -> None: ...
    async def replace_document(self, document: SourceDocument, units: list[KnowledgeUnit]) -> None: ...
    async def delete_document(self, document_id: str) -> None: ...
    async def delete_documents_not_in(self, document_ids: set[str]) -> int: ...
    async def search(self, query: str, top_k: int, filters: dict) -> list[EvidenceCandidate]: ...


class GraphIndexAdapter(Protocol):
    async def initialize(self) -> None: ...
    async def close(self) -> None: ...
    async def replace_document(
        self, document: SourceDocument, units: list[KnowledgeUnit], links: list[str]
    ) -> None: ...
    async def delete_document(self, document_id: str) -> None: ...
    async def delete_documents_not_in(self, document_ids: set[str]) -> int: ...
    async def search(self, query: str, top_k: int, filters: dict) -> list[EvidenceCandidate]: ...
